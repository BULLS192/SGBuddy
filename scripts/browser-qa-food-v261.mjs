import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},colorScheme:'light',locale:'en-SG'});
await context.addInitScript(()=>{localStorage.setItem('sgc-persona-onboarded','1');localStorage.setItem('sgc-mode','resident')});
const page=await context.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));
try{
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded',timeout:30000});
 await page.waitForFunction(()=>document.querySelector('#appVersion')?.textContent==='v3.9.0',{timeout:30000});
 const sheet=page.locator('#locationSheet');
 await sheet.waitFor({state:'visible',timeout:2500}).catch(()=>{});
 if(await sheet.isVisible())await page.locator('#notNowLocationButton').click();
 await page.locator('#navPlaces').click();
 await page.locator('[data-discover-tab="eat"]').click();
 await page.locator('#foodExplorer').waitFor({state:'visible'});
 await page.waitForFunction(()=>window.__SGBUDDY_FOOD_TOOLS__==='v2.6',{timeout:20000});
 await page.waitForFunction(()=>document.querySelector('#foodPickNote')?.textContent?.includes('guide-listed food candidates'),{timeout:16000});
 const originalCount=await page.locator('#foodCount').textContent();
 assert.ok(Number.parseInt(originalCount,10)>=140,'Guide-backed and original food stalls should merge without loss');
 await page.locator('#foodAwardYear').selectOption('2026');
 const guideCount=await page.locator('#foodCount').textContent();
 assert.ok(Number.parseInt(guideCount,10)>=50,'2026 guide filter should include additional listings');
 await page.locator('#foodPickArea').selectOption('Toa Payoh');
 await page.locator('#foodPickCraving').selectOption('noodles');
 await page.locator('#foodPickButton').click();
 await page.locator('#foodPickResult .food-picked-card').first().waitFor({state:'visible'});
 const suggestion=await page.locator('#foodPickResult').textContent();
 assert.ok(/Toa Payoh/.test(suggestion),'Expected Toa Payoh match');
 assert.ok(/opening hours/.test(suggestion),'Unknown live operation disclaimer required');
 const save=page.locator('#foodPickResult [data-food-pick-save]').first();
 await save.click();
 assert.equal(await save.getAttribute('aria-pressed'),'true','Save pick should persist selected state');
 await page.reload({waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('#appVersion')?.textContent==='v3.9.0',{timeout:30000});
 await page.locator('#navPlaces').click();
 await page.locator('[data-discover-tab="eat"]').click();
 await page.locator('#foodPickSaved').click();
 assert.ok((await page.locator('#foodPickResult').textContent()).includes('Toa Payoh'),'Saved food pick should survive reload');
 await page.locator('#foodToolServices').click();
 await page.locator('[data-food-service="reservations"]').click();
 const links=await page.locator('#foodServiceResults a').allTextContents();
 assert.ok(links.some(x=>x.includes('Chope')),'Chope booking handoff missing');
 assert.ok(links.some(x=>x.includes('Eatigo')),'Eatigo external deals handoff missing');
 await page.locator('[data-food-service="rescue"]').click();
 assert.ok((await page.locator('#foodServiceResults').textContent()).includes('treatsure'),'Food rescue service missing');
 await page.locator('[data-discover-tab="apps"]').click();
 await page.locator('#everydayApps').waitFor({state:'visible'});
 await page.locator('[data-app-view="all"]').click();
 await page.waitForFunction(()=>Number.parseInt(document.querySelector('#appLibraryCount')?.textContent||'0',10)>=79,{timeout:16000});
 await page.locator('#appLibrarySearch').fill('Burpple');
 assert.ok((await page.locator('#appLibraryCards').textContent()).includes('Burpple'));
 await page.locator('#appLibrarySearch').fill('Jiak Simi');
 assert.ok((await page.locator('#appLibraryCards').textContent()).includes('Jiak Simi'));
 await page.locator('[data-discover-tab="eat"]').click();
 const dimensions=await page.evaluate(()=>({viewport:innerWidth,scroll:document.documentElement.scrollWidth,tool:document.querySelector('#foodToolsV261')?.getBoundingClientRect().width}));
 assert.ok(dimensions.tool>=275&&dimensions.tool<=dimensions.viewport+5,'Mobile food card must fit phone viewport: '+JSON.stringify(dimensions));
 assert.ok(dimensions.scroll<=dimensions.viewport+16,'Mobile page overflow regression: '+JSON.stringify(dimensions));
 const colours=await page.evaluate(()=>{const b=document.querySelector('#foodPickButton');const x=getComputedStyle(b);return {bg:x.backgroundColor,fg:x.color}});
 assert.equal(colours.fg,'rgb(255, 255, 255)','Light theme food primary action must retain white text');
 assert.ok(!errors.length,'Unhandled JavaScript errors: '+errors.join(' / '));
 console.log('SGBuddy Food v2.6 CHROMIUM PASS: 2026 guide leads, Merli picker, saved state, Chope/Eatigo links, treatsure, new apps, 390px light-mode contrast');
}finally{await browser.close()}
