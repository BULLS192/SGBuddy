import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseIcs,publicCandidates,icsDay} from '../lib/events-ical-v470.mjs';
const raw='BEGIN:VCALENDAR\r\nVERSION:2.0\r\nBEGIN:VEVENT\r\nSUMMARY:Open Art Fair\r\nDTSTART;TZID=Asia/Singapore:20261017T120000\r\nDTEND;TZID=Asia/Singapore:20261018T200000\r\nLOCATION:Hall 3\r\nEND:VEVENT\r\nBEGIN:VEVENT\r\nSUMMARY:Private Meeting\r\nDESCRIPTION:Private Event\r\nDTSTART:20261017T130000Z\r\nDTEND:20261017T160000Z\r\nEND:VEVENT\r\nBEGIN:VEVENT\r\nSUMMARY:Cancelled Show\r\nSTATUS:CANCELLED\r\nDTSTART:20261017T130000Z\r\nDTEND:20261017T160000Z\r\nEND:VEVENT\r\nEND:VCALENDAR';
const parsed=parseIcs(raw);
assert.equal(parsed.length,3);
assert.equal(icsDay('20261016T170000Z'),'2026-10-17');
assert.equal(icsDay('20261017T120000'),'2026-10-17');
const source={id:'test-feed',sourceId:'suntec-convention',publicPage:'https://www.suntecsingapore.com/visit-events',venue:'Suntec Singapore'};
const result=publicCandidates(parsed,source,'2026-10-13');
assert.equal(result.length,1);
assert.equal(result[0].status,'needs-review');
assert.equal(result[0].title,'Open Art Fair');
assert.equal(result[0].startDate,'2026-10-17');
assert.equal(result[0].endDate,'2026-10-18');
assert.equal(result[0].sourceUrl,source.publicPage);
const config=JSON.parse(readFileSync('data/event-feeds-v470.json','utf8'));
assert.ok(config.feeds.every(f=>f.mode==='review-only'&&new URL(f.url).host===new URL(f.publicPage).host));
const queue=JSON.parse(readFileSync('data/events-review-queue-v470.json','utf8'));
assert.ok(queue.candidates.every(c=>c.status==='needs-review'));
assert.ok(readFileSync('.github/workflows/events-refresh-v470.yml','utf8').includes('sync-event-feeds-v470'));
console.log('V4.7 review-only ICS parser and feed configuration QA passed');
