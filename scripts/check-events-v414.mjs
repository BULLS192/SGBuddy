/* V4.14 official publisher title provenance: no auto-curation. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseVenueDetail,extractVenueTitle} from '../lib/events-public-html-v490.mjs';
import {triageEventCandidates} from '../lib/events-review-v413.mjs';
const sources=JSON.parse(readFileSync('data/event-venue-sources-v490.json','utf8'));
const expo=sources.sources.find(s=>s.sourceId==='expo'),url='https://www.singaporeexpo.com.sg/events-at-expo/the-makers-ground-at-expo/';
const body=extra=>'<html><head>'+extra+'</head><body><h1>Events @ EXPO</h1><p>Date</p><p>31 Oct – 1 Nov 2026</p><p>Venue</p><p>Hall 2</p><p>Admission Type</p><p>Open to Public (Free)</p></body></html>';
const og=parseVenueDetail(body('<meta content="The Makers Ground @ EXPO" property="og:title">'),expo,url,'2026-10-14');
assert.equal(og.title,'The Makers Ground @ EXPO');assert.equal(og.titleSource,'og:title');assert.equal(og.titleReviewRequired,false);
const twitter=parseVenueDetail(body('<meta name="twitter:title" content="The Makers Ground">'),expo,url,'2026-10-14');
assert.equal(twitter.titleSource,'twitter:title');assert.equal(twitter.title,'The Makers Ground');
const structured=parseVenueDetail(body('<script type="application/ld+json">{"@context":"https://schema.org","@type":"Event","name":"Makers Fair @ EXPO"}</script>'),expo,url,'2026-10-14');
assert.equal(structured.titleSource,'json-ld-event');assert.equal(structured.title,'Makers Fair @ EXPO');
const document=parseVenueDetail(body('<title>Official Makers Expo | Singapore EXPO</title>'),expo,url,'2026-10-14');
assert.equal(document.title,'Official Makers Expo');assert.equal(document.titleSource,'document-title');
const h1=parseVenueDetail(body('<meta property="og:title" content="Correct title">').replace('Events @ EXPO</h1>','Source Event Name</h1>'),expo,url,'2026-10-14');
assert.equal(h1.titleSource,'h1');assert.equal(h1.title,'Source Event Name');
const slugOnly=parseVenueDetail(body(''),expo,url,'2026-10-14');
assert.equal(slugOnly.title,'the makers ground at expo');assert.equal(slugOnly.titleSource,'url-slug');assert.equal(slugOnly.titleReviewRequired,true);
assert.ok(/verify title/.test(slugOnly.reason));
const publicData={events:[]},sourceRegistry={sources:[{id:'expo',url:expo.url}]};
const report=triageEventCandidates({candidates:[slugOnly,og]},publicData,sourceRegistry,'2026-10-14');
assert.equal(report.total,2);
assert.equal(report.held,1);
assert.ok(report.rows.find(x=>x.titleSource==='url-slug')===undefined,'triage rows may intentionally omit publisher-specific provenance');
assert.ok(report.rows.find(x=>x.title===slugOnly.title).flags.includes('unverified-url-title'));
assert.ok(report.rows.every(x=>x.approvalAllowed===false));
assert.ok(extractVenueTitle('<h1>Events @ EXPO</h1>',url).titleReviewRequired);
assert.equal(parseVenueDetail(body(''),expo,url,'2026-11-02'),null,'expired events must never enter future queue');
console.log('V4.14 Events title QA PASS: H1, publisher OG/Twitter, Event JSON-LD, page title, URL fallback holds; editorial firewall intact.');
