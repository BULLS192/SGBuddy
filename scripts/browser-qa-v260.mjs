import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900},locale:'en-SG',acceptDownloads:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>{localStorage.setItem('sgc-persona-onboarded','1');localStorage.setItem('sgc-mode','visitor');localStorage.setItem('sgc-location-choice','not-now')});
const ready=async()=>{await page.waitForFunction(()=>document.querySelector('#appVersion')?.textContent==='v4.12.0',{timeout:30000});await page.locator('#navPlaces').click()};
try{
 await page.goto('http://127.0.0.1:8765/',{waitUntil:'domcontentloaded',timeout:30000});await ready();
 await page.locator('[data-discover-tab="trip"]').click();
 await page.locator('#myTripPlanner').waitFor({state:'visible'});
 await page.locator('#tripNewName').fill('Singapore December');
 await page.locator('#tripStartDate').fill('2026-12-01');
 await page.locator('#tripNumberOfDays').fill('3');
 await page.locator('#tripCreateForm button[type="submit"]').click();
 await page.locator('.trip-day-tabs button').first().waitFor({state:'visible'});
 assert.equal(await page.locator('.trip-day-tabs button').count(),3);
 await page.waitForFunction(()=>Array.isArray(window.SGBUDDY_DISCOVER_PLACES)&&window.SGBUDDY_DISCOVER_PLACES.length>50,{timeout:25000});
 await page.locator('#tripSearch').fill('Maxwell Food Centre');
 await page.locator('[data-trip-add-search]').first().click();
 assert.equal(await page.locator('.trip-stop').count(),1,'Search result should add a stop');
 await page.locator('[data-trip-time="0"]').fill('12:30');
 await page.locator('[data-trip-note="0"]').fill('Lunch plans');
 await page.locator('[data-trip-note="0"]').press('Tab');
 await page.locator('[data-trip-day="1"]').click();
 await page.locator('[name="customName"]').fill('Meet friends at hotel');
 await page.locator('[name="customArea"]').fill('Marina Bay');
 await page.locator('#tripCustomForm button[type="submit"]').click();
 assert.equal(await page.locator('.trip-stop').count(),1,'Custom stop should be added to Day 2');
 await page.reload({waitUntil:'domcontentloaded'});await ready();
 await page.locator('[data-discover-tab="trip"]').click();
 assert.equal(await page.locator('#tripSelect option').count(),1);
 await page.locator('[data-trip-day="0"]').click();
 assert.equal(await page.locator('.trip-stop').count(),1,'Trip must persist after reload');
 assert.equal(await page.locator('[data-trip-time="0"]').inputValue(),'12:30');
 assert.equal(await page.locator('[data-trip-note="0"]').inputValue(),'Lunch plans');
 await page.locator('[data-trip-transfer="0"]').selectOption({value:'2'});
 assert.equal(await page.locator('.trip-stop').count(),0,'Moving across days clears the source day');
 await page.locator('[data-trip-day="2"]').click();
 assert.equal(await page.locator('.trip-stop').count(),1,'Moved stop should appear on day 3');
 await page.locator('#tripCreateDetails summary').click();
 await page.locator('#tripNewName').fill('Second trip');
 await page.locator('#tripStartDate').fill('2027-02-01');
 await page.locator('#tripNumberOfDays').fill('2');
 await page.locator('#tripCreateForm button[type="submit"]').click();
 assert.equal(await page.locator('#tripSelect option').count(),2,'Multiple trips supported');
 await page.locator('#tripSelect').selectOption({label:'Singapore December'});
 await page.locator('[data-discover-tab="eat"]').click();
 await page.locator('[data-trip-add-place]').first().click();
 await page.locator('[data-discover-tab="trip"]').click();
 assert.ok(await page.locator('.trip-stop').count()>=1,'Place-card Add to Trip should work');
 await page.locator('#sgbLanguage').selectOption('zh-CN');
 assert.equal(await page.locator('[data-discover-tab="trip"]').textContent(),'我的行程');
 assert.equal(await page.locator('#myTripPlanner h3').textContent(),'我的行程');
 await page.setViewportSize({width:375,height:812});
 assert.ok(await page.locator('#myTripPlanner').evaluate(el=>el.getBoundingClientRect().width<=innerWidth+8),'Trip panel should fit mobile width');
 assert.equal(errors.length,0,'JS page errors: '+errors.join(' | '));
 console.log('SGBuddy V2.6 CHROMIUM PASS: trip creation, directory search, custom stops, day transfers, persistence, multiple trips, venue add, Chinese and mobile width.');
}finally{await browser.close()}
