import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {STORE_KEY,MAX_TRIPS,MAX_DAYS,newTrip,dayDate,validPlace,addStop,moveStop,moveDay,editStop,hydrate,shareText} from '../lib/trip-v260.mjs';
const read=p=>readFileSync(p,'utf8');
const trip=newTrip('Singapore visit','2026-12-30',3);
assert.equal(trip.days.length,3);
assert.equal(dayDate(trip.startDate,2),'2027-01-01','Dates must roll over the year');
assert.throws(()=>newTrip('bad','2026-02-30',3));
assert.equal(newTrip('Bounded','2026-12-01',100).days.length,MAX_DAYS);
const p1={id:'SGP-0001',name:'Maxwell Food Centre',area:'Chinatown',kind:'Eat',sourceUrl:'https://data.gov.sg/'};
const p2={id:'SGP-0002',name:'Old Airport Road Food Centre',area:'Geylang',kind:'Eat'};
assert.equal(addStop(trip,0,p1),true);
assert.equal(addStop(trip,0,p1),false,'Cannot duplicate a venue in same day');
assert.equal(addStop(trip,0,p2),true);
assert.equal(moveStop(trip,0,1,-1),true);
assert.equal(trip.days[0][0].place.id,'SGP-0002');
assert.equal(moveStop(trip,0,0,-1),false,'Cannot reorder outside day');
assert.equal(editStop(trip.days[0][0],'time','14:30'),true);
assert.equal(editStop(trip.days[0][0],'time','25:00'),false);
assert.equal(editStop(trip.days[0][0],'note','Fun day!'),true);
assert.equal(editStop(trip.days[0][0],'done',true),true);
assert.equal(moveDay(trip,0,0,1),true);
assert.equal(trip.days[1].length,1);
const copy=shareText(trip);
assert.ok(copy.includes('Day 2')&&copy.includes('14:30')&&copy.includes('Fun day!')&&copy.includes('No reservations are made.'));
assert.equal(shareText(null),'');
assert.equal(validPlace({id:'foo',name:''}),null);
const restored=hydrate({activeId:trip.id,trips:[trip]});
assert.equal(restored.activeId,trip.id);
assert.equal(restored.trips[0].days[1][0].done,true);
const bad=hydrate({activeId:'bogus',trips:[null,{name:'bad',startDate:'yesterday',days:[[]]},...Array.from({length:50},(_,i)=>newTrip('test','2026-12-01',1))]});
assert.ok(bad.trips.length<=MAX_TRIPS,'Hydration should cap trips');
assert.equal(hydrate({activeId:'bad',trips:[{name:'bogus',startDate:'not-date',days:[[]]}]}).activeId,null);
const ui=read('app-trip-v260.js'),dis=read('app-v120.js'),travel=read('app-travel-v250.js'),ux=read('app-ux-v160.js'),html=read('index.html'),boot=read('app-v090.js'),sw=read('sw.js'),css=read('trip-v260.css');
for(const s of ['sgbuddy:trip-add-place','sgbuddy:discover-places-ready','sgbuddy:discover-tab','sgbuddy:language','tripCreateForm','tripCustomForm','tripShare','tripDownload','tripDelete','data-trip-time','data-trip-note','data-trip-day','data-trip-transfer'])assert.ok(ui.includes(s),'Missing My Trip integration '+s);
assert.equal(STORE_KEY,'sgbuddy-my-trips-v260');
assert.ok(dis.includes("['trip','My Trip']")&&dis.includes('data-trip-add-place')&&dis.includes('myTripPlanner')&&dis.includes('sgbuddy:discover-places-ready'),'Discover integration incomplete');
assert.ok(ux.includes("tab==='trip'"),'Legacy Explore results must hide');
assert.ok(travel.includes("trip:'My Trip'")&&travel.includes("trip:'我的行程'")&&travel.includes('data-travel-trip'),'Travel Prep not integrated');
assert.ok(boot.includes("import('/app-trip-v260.js')")&&boot.includes("2.6.0"),'V2.6 version/import missing');
assert.ok(html.includes('trip-v260.css')&&html.includes('v2.6.0'));
for(const asset of ['/app-trip-v260.js','/lib/trip-v260.mjs','/trip-v260.css'])assert.ok(sw.includes(asset),'PWA shell missing '+asset);
assert.ok(/sgbuddy-shell-v5[4-9]/.test(sw));
for(const v of ['[hidden]','data-ux-theme="light"','max-width:680px','focus-visible'])assert.ok(css.includes(v),'Style missing '+v);
console.log('SGBuddy V2.6 My Trip PASS: model limits, saved schema, daily edits, bilingual Discover integration and offline PWA.');
