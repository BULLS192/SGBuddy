import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const catalog=JSON.parse(read('data/operator-listings-v220.json'));
const svc=JSON.parse(read('data/services-v210.json'));
const menu=JSON.parse(read('data/vendor-menus-v210.json'));
const app=read('app-v120.js'),food=read('app-food-v180.js'),sw=read('sw.js'),index=read('index.html');
assert.equal(catalog.places.length,17,'First-party branch dataset changed unexpectedly');
assert.equal(catalog.counts.operatorSupermarkets,15);
assert.equal(catalog.counts.operatorFoodLocations,2);
const locIds=new Set(),byPostal=new Map();
for(const p of catalog.places){
 assert.ok(p.id.startsWith('SGV-')&&!locIds.has(p.id));locIds.add(p.id);
 assert.ok(/^https:\/\//.test(p.sourceUrl));
 assert.match(p.postal,/^\d{6}$/,'Every first-party location must have a documented postal');
 assert.equal(p.status,'operator-listed');
 assert.equal(p.operatingStatus,'not-live-confirmed','Must not infer an open-now status');
 assert.equal(p.hoursCurrentNow,false);
 assert.equal(p.verifiedScope,'operator-published-branch-address');
 assert.equal(p.sourceCheckedOn,'2026-10-11');
 assert.ok(p.name&&p.address&&p.modes.length===4);
 const key=(p.operator||'')+'|'+p.postal;assert.ok(!byPostal.has(key),'Duplicate operator/postal entry: '+key);byPostal.set(key,p.id);
}
assert.ok(svc.places.length>=1950,'Services library missing');
const historical=svc.places.filter(p=>p.category==='Supermarket (historical licence)');
assert.ok(historical.length>=470);
assert.ok(historical.every(p=>p.operatingStatus==='unverified'&&p.lat===null&&p.lon===null),'Never invent current status or GIS for historical licences');
assert.ok(svc.places.filter(p=>p.category==='CHAS clinic').every(p=>p.operatingStatus==='unverified'),'Do not assert clinic current participation');
for(const str of ['data/operator-listings-v220.json','operator-listed','Supermarket (historical licence)',"sourceFilter==='operator'",'current CHAS locator','sourceCoverageAsOf','sourceCheckedOn'])assert.ok(app.includes(str),'Discover trust UI missing '+str);
assert.ok(app.includes("liveBrandPostal.has('shengsiong|'"),'Retired Sheng Siong licence branch collision must be suppressed');
assert.ok(food.includes('Menu-published branch:')&&food.includes('locationSpecific&&x.venueAddress'),'Vendor menu branch applicability disclaimer missing');
const chiew=menu.items.filter(m=>m.vendor==='Chiew Kee Soya Sauce Chicken');
assert.equal(chiew.length,10);
assert.ok(chiew.every(x=>x.locationSpecific&&x.venueAddress==='32 Upper Cross Street, Singapore 058339'),'Chiew Kee branch menu must not be generalized to another site');
for(const str of ['/data/operator-listings-v220.json','/verification-v220.css'])assert.ok(sw.includes(str));
assert.ok(index.includes('/verification-v220.css'));
assert.ok(read('.github/workflows/library-freshness-v210.yml').includes('scripts/audit-operator-v220.mjs'),'Weekly first-party audit not wired');
assert.ok(read('scripts/audit-operator-v220.mjs').includes("operatingStatus:'NOT_VERIFIED_LIVE'"),'Operator source checker must never set live status');
console.log('SGBuddy V2.2 validation PASS: 15 retailer-listed branches, 2 operator restaurants, source scopes and historical safeguards');
