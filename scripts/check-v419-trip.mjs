import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {newTrip,addStop,editStop,hydrate,dayOverview,dayWalkingRouteUrl,STORE_KEY} from '../lib/trip-v260.mjs';
const t=newTrip('Test','2026-11-01',2);
assert.deepEqual(dayOverview(t,0),{count:0,timed:0,untimed:0,missingAddress:0,timeConflicts:0});
assert.equal(dayWalkingRouteUrl(t,0),'');
for(let i=0;i<7;i++)assert.ok(addStop(t,0,{id:'stop-'+i,name:'Location '+i,area:'Singapore',address:i<3?'Address '+i:''}));
editStop(t.days[0][0],'time','09:00');editStop(t.days[0][1],'time','09:00');editStop(t.days[0][2],'time','13:00');
const state=JSON.stringify(t),q=dayOverview(t,0);
assert.deepEqual(q,{count:7,timed:3,untimed:4,missingAddress:4,timeConflicts:1});
const url=new URL(dayWalkingRouteUrl(t,0));assert.equal(url.origin,'https://www.google.com');
assert.equal(url.pathname,'/maps/dir/');assert.equal(url.searchParams.get('travelmode'),'walking');
assert.ok(url.searchParams.get('origin').includes('Location 0'));
assert.ok(url.searchParams.get('destination').includes('Location 4'));
assert.equal(url.searchParams.get('waypoints').split('|').length,3);
assert.equal(new URL(dayWalkingRouteUrl(t,0,{maxStops:2})).searchParams.has('waypoints'),false);
assert.equal(JSON.stringify(t),state,'Read-only analysis must not mutate trips');
assert.deepEqual(dayOverview(hydrate({activeId:t.id,trips:[t]}).trips[0],0),q);
assert.equal(STORE_KEY,'sgbuddy-my-trips-v260');
const ui=readFileSync('app-trip-v260.js','utf8');
for(const tag of ['data-trip-day-insights','data-trip-walking-route','dayOverview','dayWalkingRouteUrl'])assert.ok(ui.includes(tag),tag);
for(const locale of ['en','zh-CN','zh-TW','ms','id','ja','ko','th','vi','fr','es','pt-BR'])assert.ok(ui.includes('"'+locale+'":'),locale);
assert.ok(readFileSync('trip-v260.css','utf8').includes('.trip-day-insights'));
console.log('My Trip 2.0 Wave 1 PASS: time collisions, missing addresses, five-stop walking handoff, no data mutation, 12 locales.');
