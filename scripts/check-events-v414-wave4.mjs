/* V4.14 final wave: sourced regions, translated controls and event-date-aware device-local trips. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {LOCALES} from '../lib/i18n-v280.mjs';
import {EVENT_AREAS,EVENT_CATEGORIES_FILTER,sourceArea,filterEventsByAreaCategory,matchingEventDay,eventFallbackDate,eventTripPlace} from '../lib/events-explore-v414.mjs';
import {EVENT_EXPLORE_KEYS,EVENT_EXPLORE_TEXT,eventExploreText} from '../lib/events-explore-i18n-v414.mjs';
import {selectWeekendPicks} from '../lib/events-weekend-v414.mjs';
import {newTrip,dayDate,addStop,validPlace} from '../lib/trip-v260.mjs';
const read=path=>JSON.parse(readFileSync(path,'utf8'));
const data=read('data/events-v470.json'),sources=read('data/event-sources-v470.json').sources,day='2026-10-14';
assert.equal(data.events.length,11,'No unapproved event additions allowed');
assert.deepEqual(EVENT_AREAS,['all','central','east','west','north','south','islandwide']);
assert.equal(sourceArea(data.events.find(e=>e.sourceId==='expo'),sources),'east');
assert.equal(sourceArea(data.events.find(e=>e.sourceId==='suntec-convention'),sources),'central');
assert.equal(sourceArea({sourceId:'missing'},sources),null);
const east=filterEventsByAreaCategory(data.events,sources,'east','all');
assert.ok(east.length>0&&east.every(e=>e.sourceId==='expo'));
const central=filterEventsByAreaCategory(data.events,sources,'central','all');
assert.ok(central.length>0&&central.every(e=>e.sourceId.startsWith('suntec-')));
const family=filterEventsByAreaCategory(data.events,sources,'all','family');
assert.ok(family.every(e=>e.category==='family'));
assert.ok(filterEventsByAreaCategory(data.events,sources,'central','music').every(e=>e.category==='music'));
assert.equal(filterEventsByAreaCategory(data.events,sources,'invalid','all').length,0);
assert.ok(selectWeekendPicks(data.events,day,'visitor',3,{sources,area:'east'}).every(e=>e.sourceId==='expo'));
assert.ok(selectWeekendPicks(data.events,day,'resident',3,{sources,category:'family'}).every(e=>e.category==='family'));
const trip=newTrip('Weekend','2026-10-16',4);
const event=data.events.find(e=>e.id==='art-riot-2026');
assert.equal(matchingEventDay(trip,event),1,'Event must land on overlapping Saturday rather than currently selected day');
assert.equal(eventFallbackDate(event,day),'2026-10-17');
assert.equal(eventTripPlace(event).id,'sgbuddy-event-art-riot-2026');
assert.equal(eventTripPlace(event).sourceUrl,event.sourceUrl);
assert.equal(validPlace(eventTripPlace(event)).kind,'Event');
assert.ok(addStop(trip,1,eventTripPlace(event)));
assert.equal(addStop(trip,1,eventTripPlace(event)),false,'Same event must not be added twice to one trip day');
assert.equal(matchingEventDay(newTrip('No overlap','2026-12-10',2),event),-1);
assert.equal(eventFallbackDate(event,'2026-10-18'),'2026-10-18','Ongoing event should create a current-date plan');
assert.equal(eventFallbackDate(event,'2026-10-19'),null,'Expired event cannot be added to My Trip');
assert.equal(eventTripPlace({...event,status:'needs-review'}),null);
assert.equal(eventTripPlace({...event,sourceUrl:'javascript:alert(1)'}),null);
assert.equal(eventTripPlace({...event,id:'INVALID ID'}),null);
for(const {code} of LOCALES){
 const messages=EVENT_EXPLORE_TEXT[code];
 assert.ok(messages,'Missing locale '+code);
 assert.equal(Object.keys(messages).length,EVENT_EXPLORE_KEYS.length);
 for(const key of EVENT_EXPLORE_KEYS)assert.ok(typeof eventExploreText(code,key)==='string'&&eventExploreText(code,key).trim().length>1,'Missing '+key+' for '+code);
}
const app=readFileSync('app-events-v470.js','utf8'),tripJs=readFileSync('app-trip-v260.js','utf8');
for(const token of ['data-event-area','data-event-category','data-event-trip','api?.addEvent','eventExploreText'])assert.ok(app.includes(token),'Missing Events integration '+token);
for(const token of ['matchingEventDay','eventFallbackDate','addEvent:event','sourceUrl','evText'])assert.ok(tripJs.includes(token),'Missing local My Trip integration '+token);
const sw=readFileSync('sw.js','utf8');
for(const path of ['/lib/events-explore-v414.mjs','/lib/events-explore-i18n-v414.mjs'])assert.ok(sw.includes(path),'Offline shell missing '+path);
const approvals=read('data/event-approvals-v490.json');
assert.equal(approvals.approvals.length,0,'Discovery must not auto-approve events');
console.log('V4.14 Wave 4 STATIC PASS: region source registry, 12 locales, event date-aware itinerary, offline modules, zero auto-approvals.');
