/* V4.14 Wave 3: no inferred event access, editor worklist, duplicate-safe publication. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseVenueDetail} from '../lib/events-public-html-v490.mjs';
import {buildEditorWorklist,editorWorklistMarkdown} from '../lib/events-editor-v414.mjs';
import {checkEditorApproval} from '../lib/events-approval-guard-v414.mjs';
const read=path=>JSON.parse(readFileSync(path,'utf8'));
const config=read('data/event-venue-sources-v490.json');
const expo=config.sources.find(s=>s.sourceId==='expo');
const url='https://www.singaporeexpo.com.sg/events-at-expo/sample-fair/';
const html=(admission='')=>'<html><h1>Sample Fair</h1><p>Date</p><p>17 Oct 2026</p><p>Venue</p><p>Hall 4</p><p>'+admission+'</p></html>';
const publicEvent=parseVenueDetail(html('Open to Public (Free)'),expo,url,'2026-10-14');
assert.equal(publicEvent.admission,'free');
assert.equal(publicEvent.admissionEvidence,'official-venue-free');
assert.equal(publicEvent.access,'public-stated');
assert.ok(publicEvent.publicAccessEvidence);
assert.equal(publicEvent.status,'needs-review','Explicit venue labels are NOT editorial approval');
const ticketed=parseVenueDetail(html('Open to Public (Ticketed Admission)'),expo,url,'2026-10-14');
assert.equal(ticketed.admission,'ticketed');assert.equal(ticketed.access,'public-stated');
const missing=parseVenueDetail(html(),expo,url,'2026-10-14');
assert.equal(missing.admission,'check');
assert.equal(missing.access,'unverified');
assert.equal(missing.admissionEvidence,null);
assert.equal(missing.publicAccessEvidence,null);
const sources=read('data/event-sources-v470.json'),published=read('data/events-v470.json'),queue=read('data/events-review-queue-v470.json');
const result=buildEditorWorklist(queue,published,sources,'2026-10-14');
assert.equal(result.total,queue.candidates.length,'Editor worklist must cover every held candidate');
const evidence=read('data/events-evidence-v419.json');
assert.equal(queue.candidates.filter(x=>evidence.records.some(r=>r.id===x.id)).length,evidence.records.length,'All newly source-checked Esplanade records remain held');
assert.equal(result.autoApproved,0);
assert.ok(result.rows.every(r=>r.approvalAllowed===false&&r.requiresEditor===true));
assert.ok(result.rows.some(r=>r.category==='already-curated'));
assert.ok(result.rows.some(r=>r.missingEvidence.includes('public access')));
assert.ok(result.rows.some(r=>r.missingEvidence.includes('permission to list')));
const markdown=editorWorklistMarkdown(result,{limit:5});
assert.ok(markdown.includes('Review-only'));
assert.ok(markdown.includes('permission to list'));
assert.ok(!markdown.includes('auto-approved for publishing'));
const today='2026-10-14',proposed={
 id:'new-sample-fair-2026',title:'Sample Fair',startDate:'2026-10-17',endDate:'2026-10-17',
 venue:'Singapore EXPO',sourceId:'expo',sourceUrl:url,status:'scheduled',admission:'free',category:'market',verifiedAt:today,
 summary:'Market',verificationMethod:'editor_approved_official_page'};
const approval={titleVerified:true,publicAccessVerified:true,reviewedAt:today,admission:'free'};
const candidate={...publicEvent,titleSource:'h1',titleReviewRequired:false};
const args={approval,row:candidate,event:proposed,published:[],accepted:[],sources:sources.sources,day:today};
assert.deepEqual(checkEditorApproval(args),[],'Clear reviewed candidate can enter the existing human-reviewed process');
const deny=(changes)=>checkEditorApproval({...args,...changes});
assert.ok(deny({approval:{...approval,publicAccessVerified:false}}).some(x=>x.includes('Public entry')));
assert.ok(deny({approval:{...approval,titleVerified:false}}).some(x=>x.includes('title')));
assert.ok(deny({approval:{...approval,admission:'check'}}).some(x=>x.includes('Admission')));
assert.ok(deny({approval:{...approval,reviewedAt:'2026-09-13'}}).some(x=>x.includes('14')));
assert.ok(deny({row:{...candidate,title:'Events @ EXPO'}}).some(x=>x.includes('provisional')));
assert.ok(deny({row:{...candidate,sourceUrl:'https://fake.example/events'}}).some(x=>x.includes('publisher host')));
assert.ok(deny({published:[{...proposed,id:'existing-event'}]}).some(x=>x.includes('Duplicate')));
assert.ok(deny({accepted:[{...proposed,id:'previously-approved'}]}).some(x=>x.includes('Duplicate')));
const publish=readFileSync('scripts/publish-reviewed-events-v490.mjs','utf8');
assert.ok(publish.includes('checkEditorApproval('),'Publisher gate must invoke added safeguards');
assert.ok(publish.includes('publicListingRightsVerified'),'Existing rights signoff must remain');
assert.ok(publish.includes("process.argv.includes('--publish')"),'No auto publish');
assert.ok(!readFileSync('.github/workflows/events-refresh-v470.yml','utf8').includes('node scripts/publish-reviewed-events-v490.mjs'),'Daily event refresh must not publish');
console.log('V4.14 WAVE 3 PASS: admission/public access evidence, all unpublished reviews, 14-day editor signoff and duplicate-proof approval gate.');
