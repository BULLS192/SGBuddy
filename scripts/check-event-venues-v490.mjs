import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {extractVenueLinks,parseVenueDetail,parseDateRange,robotsAllows,readableHtml} from '../lib/events-public-html-v490.mjs';
const config=JSON.parse(readFileSync('data/event-venue-sources-v490.json','utf8'));
const keys=config.sources.map(x=>x.id);
assert.deepEqual(keys,['expo-html','suntec-city-html','313-html']);
const expo=config.sources[0];
assert.ok(extractVenueLinks('<a href="/events-at-expo/caps-cardshow/">Details</a><a href="https://evil.com/events-at-expo/fake/">Bad</a><a href="/events-at-expo/">Index</a><a href="/events-at-expo/caps-cardshow/">Dup</a>',expo).length===1);
assert.deepEqual(parseDateRange('31 Oct – 1 Nov 2026'),{startDate:'2026-10-31',endDate:'2026-11-01'});
assert.deepEqual(parseDateRange('17 – 18 Oct 2026'),{startDate:'2026-10-17',endDate:'2026-10-18'});
assert.deepEqual(parseDateRange('02 Oct 26 - 24 Oct 26'),{startDate:'2026-10-02',endDate:'2026-10-24'});
assert.deepEqual(parseDateRange('17 Oct 2026'),{startDate:'2026-10-17',endDate:'2026-10-17'});
assert.equal(parseDateRange('30 Feb 2026')?.startDate,null);
const expoHtml='<html><h1>CAPS Cardshow</h1><p>Date</p><p>31 Oct – 1 Nov 2026</p><p>Time</p><p>10:00 – 21:00</p><p>Venue</p><p>Hall 6A</p><p>Admission Type</p><p>Open to Public (Free)</p></html>';
const event=parseVenueDetail(expoHtml,expo,'https://www.singaporeexpo.com.sg/events-at-expo/caps-cardshow/','2026-10-13');
assert.ok(event);assert.equal(event.admission,'free');assert.equal(event.status,'needs-review');assert.equal(event.endDate,'2026-11-01');assert.equal(event.sourceId,'expo');
assert.equal(event.titleSource,'h1');assert.equal(event.titleReviewRequired,false);
assert.equal(parseVenueDetail(expoHtml.replace('Open to Public (Free)','By Invitation Only'),expo,event.sourceUrl,'2026-10-13'),null);
assert.equal(parseVenueDetail(expoHtml,expo,event.sourceUrl,'2026-11-02'),null);
const mall=config.sources[2];
const mallHtml='<h1>Spooky Celebration</h1><p>18 September - 1 November 2026</p>';
const offer=parseVenueDetail(mallHtml,mall,'https://www.313somerset.com.sg/whats-on/offers/spooky/','2026-10-13');
assert.equal(offer.kind,'promotion');assert.equal(offer.admission,'check');
const robots='User-agent: *\nDisallow: /events-at-expo/private\nAllow: /events-at-expo/private-public\n';
assert.equal(robotsAllows(robots,'/events-at-expo/private/'),false);
assert.equal(robotsAllows(robots,'/events-at-expo/private-public/'),true);
assert.equal(robotsAllows(robots,'/events-at-expo/public/'),true);
assert.ok(readableHtml('<h1>Singapore &amp; Friends</h1>').includes('Singapore & Friends'));
assert.ok(readFileSync('.github/workflows/events-refresh-v470.yml','utf8').includes('sync-event-venues-v490.mjs'));
console.log('V4.9 HTML discovery QA passed: date ranges, admission gating, promotions and robots safety.');
