import assert from 'node:assert/strict';
import {newTrip,addStop} from '../lib/trip-v260.mjs';
import {tripPublishedEvents} from '../lib/trip-published-events-v421.mjs';
const trip=newTrip('Festival','2026-10-17',3);
const sources=[{id:'official',url:'https://events.example.org/whats-on'}];
const e=(id,startDate,endDate,more={})=>({id,title:id+' Event',venue:'Marina Bay',startDate,endDate,status:'scheduled',verifiedAt:'2026-10-13',verificationMethod:'official_venue_page',sourceId:'official',sourceUrl:'https://events.example.org/programme/'+id,...more});
const good=e('good-event','2026-10-17','2026-10-18');
const multi=e('multi-day-event','2026-10-16','2026-10-19');
const expired=e('old-event','2026-10-01','2026-10-12');
const later=e('far-event','2026-10-21','2026-10-23');
const draft=e('review-candidate','2026-10-17','2026-10-18',{status:'needs-review'});
const unverified=e('missing-proof','2026-10-17','2026-10-18',{verificationMethod:''});
const spoof=e('spoofed-event','2026-10-17','2026-10-17',{sourceUrl:'https://evil.example.org/listing'});
const cancelled=e('cancelled-event','2026-10-18','2026-10-18',{status:'cancelled'});
const snapshot=[good,multi,expired,later,draft,unverified,spoof,cancelled];
const original=JSON.stringify(trip);
const hits=tripPublishedEvents(trip,snapshot,sources,'2026-10-15');
assert.deepEqual(hits.map(x=>x.id),['multi-day-event','good-event']);
assert.ok(hits.every(x=>x.dayIndex===0));
assert.ok(hits.every(x=>x.sourceState==='snapshot'));
assert.deepEqual(tripPublishedEvents(trip,snapshot,sources,'2026-10-15',{limit:1}).map(x=>x.id),['good-event']);
assert.equal(tripPublishedEvents(trip,snapshot,sources,'2026-10-15',{limit:0}).length,0);
assert.equal(tripPublishedEvents(trip,[good],sources,'2026-12-01').length,0);
assert.equal(tripPublishedEvents(trip,[good],[], '2026-10-15').length,0);
assert.equal(tripPublishedEvents(trip,[good],sources,'invalid').length,0);
assert.ok(addStop(trip,0,{id:'sgbuddy-event-good-event',name:'Already planned'}));
assert.deepEqual(tripPublishedEvents(trip,[good,multi],sources,'2026-10-15').map(x=>x.id),['multi-day-event']);
assert.equal(JSON.stringify(trip).includes('Already planned'),true);
assert.notEqual(JSON.stringify(trip),original);
assert.equal(tripPublishedEvents(trip,[good],sources,'2026-10-30').length,0);
assert.equal(tripPublishedEvents(trip,[good],sources,'2026-10-15')[0],undefined);
console.log('V4.21 PUBLISHED EVENTS PASS: trip date range, verified hosts, held/cancelled/expired excluded, duplicates avoided, stale status guarded.');
