import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {newTrip,addStop,editStop} from '../lib/trip-v260.mjs';
import {SHARE_PARAM,MAX_LINK_CHARS,MAX_FILE_BYTES,snapshot,fromSnapshot,encodeTrip,decodeTrip,buildTripUrl,getLinkCode,stripShareHash,exportTripJSON,importTripJSON} from '../lib/trip-share-v270.mjs';
const trip=newTrip('Singapore 家庭计划','2027-01-30',3);
addStop(trip,0,{id:'SGP-0001',name:'Maxwell 美食中心',area:'Chinatown',kind:'Eat'});
editStop(trip.days[0][0],'time','12:30');editStop(trip.days[0][0],'note','Meet at MRT, bring water.');
addStop(trip,2,{id:'manual-1',name:'Visit Friends',area:'Marina Bay'});
const encoded=encodeTrip(trip);
assert.ok(encoded&&encoded.length<MAX_LINK_CHARS&&!encoded.includes('家'), 'URL-safe bounded UTF-8 payload');
const restored=decodeTrip(encoded);
assert.equal(restored.name,trip.name);assert.equal(restored.days.length,3);
assert.equal(restored.days[0][0].place.name,'Maxwell 美食中心');
assert.equal(restored.days[0][0].time,'12:30');assert.equal(restored.days[0][0].note,'Meet at MRT, bring water.');
assert.notEqual(restored.id,trip.id,'Cross-device import must create an independent trip copy');
assert.equal(restored.days[2][0].place.name,'Visit Friends');
assert.deepEqual(snapshot(restored),snapshot(trip));
const url=buildTripUrl('https://sgbuddy.omnidite.com/?other=secret#profile=not-a-token',trip);
assert.ok(url.startsWith('https://sgbuddy.omnidite.com/#sgtrip='),'Share URL must discard auth/query/hash');
assert.equal(getLinkCode(new URL(url).hash),encoded);
assert.equal(stripShareHash('https://sgbuddy.omnidite.com/?foo=bar#sgtrip='+encoded+'&view=places'),'/?foo=bar#view=places');
assert.equal(getLinkCode('#profile=other'),null);
assert.throws(()=>decodeTrip('evil<script>'),/invalid/i);
assert.throws(()=>decodeTrip('a'.repeat(MAX_LINK_CHARS+1)),/invalid/i);
assert.throws(()=>fromSnapshot({v:2,n:'abc',s:'2027-01-01',d:[[]]}),/invalid/i);
assert.throws(()=>fromSnapshot({v:1,n:'abc',s:'2027-01-01',d:[Array.from({length:31},()=>['a','b','','','','','',0])]}),/limit/i);
assert.throws(()=>fromSnapshot({v:1,n:'abc',s:'2027-01-01',d:[[ ['a','b','','','','25:00','',0] ]]}),/permitted/i);
assert.throws(()=>decodeTrip(encodeTrip(newTrip('test','2027-01-01',1)).slice(0,-2)),/invalid|corrupt/i);
const file=exportTripJSON(trip);
assert.equal(importTripJSON(file).days[2][0].place.name,'Visit Friends');
assert.throws(()=>importTripJSON('{"format":"wrong"}'),/unsupported/i);
assert.throws(()=>importTripJSON('a'.repeat(MAX_FILE_BYTES+1)),/large/i);
const ui=readFileSync('app-share-v270.js','utf8'),app=readFileSync('app-trip-v260.js','utf8'),html=readFileSync('index.html','utf8'),boot=readFileSync('app-v090.js','utf8'),sw=readFileSync('sw.js','utf8'),css=readFileSync('trip-share-v270.css','utf8');
for(const keyword of ['tripMakeLink','tripCopyLink','tripSystemShare','tripExportJson','tripImportJson','tripImportShared','tripDismissShared','sgbuddy:trip-rendered'])assert.ok(ui.includes(keyword),'Share UI missing '+keyword);
assert.equal(SHARE_PARAM,'sgtrip');
assert.ok(app.includes('SGBUDDY_TRIP_API')&&app.includes('importCopy')&&app.includes('sgbuddy:trip-rendered'),'Safe import API missing');
assert.ok(boot.includes("import('/app-share-v270.js')")&&boot.includes('4.1.0'));
assert.ok(html.includes('v4.1.0')&&html.includes('/trip-share-v270.css'));
assert.ok(sw.includes('/app-share-v270.js')&&sw.includes('/lib/trip-share-v270.mjs')&&sw.includes('/trip-share-v270.css')&&sw.includes('sgbuddy-shell-v74'));
assert.ok(css.includes('data-ux-theme="light"')&&css.includes('max-width:660px')&&css.includes('focus-visible'));
console.log('SGBuddy V2.7 sharing model PASS: Unicode, data limits, link safety, portable files, collaboration copy model, PWA integration.');
