import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {singaporeDate} from '../lib/calendar-v460.mjs';
import {isValidDay,weekendWindow,compileEvents,upcomingEvents,eventFreshness,normalizedKey} from '../lib/events-v470.mjs';
const intake=JSON.parse(readFileSync('data/events-intake-v470.json','utf8'));
const sources=JSON.parse(readFileSync('data/event-sources-v470.json','utf8'));
const published=JSON.parse(readFileSync('data/events-v470.json','utf8'));
const checks=compileEvents(intake,sources,published.asOf);
assert.equal(checks.events.length,published.events.length);
assert.equal(JSON.stringify(checks.events),JSON.stringify(published.events));
assert.deepEqual(weekendWindow('2026-10-13'),{start:'2026-10-17',end:'2026-10-18'});
assert.deepEqual(weekendWindow('2026-10-17'),{start:'2026-10-17',end:'2026-10-18'});
assert.deepEqual(weekendWindow('2026-10-18'),{start:'2026-10-17',end:'2026-10-18'});
assert.deepEqual(weekendWindow('2026-10-19'),{start:'2026-10-24',end:'2026-10-25'});
assert.deepEqual(weekendWindow('2026-12-31'),{start:'2027-01-02',end:'2027-01-03'});
assert.ok(!isValidDay('2026-02-30'));
assert.ok(isValidDay('2026-10-13'));
assert.ok(upcomingEvents(intake.events,'2026-10-13','weekend').length>=5);
assert.ok(upcomingEvents(intake.events,'2026-10-19','weekend').some(e=>e.id==='the-car-expo-2026'));
assert.deepEqual(upcomingEvents(intake.events,'2026-10-13','free').map(e=>e.id).includes('art-riot-2026'),false);
assert.ok(upcomingEvents(intake.events,'2026-11-02').length===0);
assert.ok(published.events.find(x=>x.id==='caps-cardshow-2026')?.admission==='free');
assert.ok(published.events.find(x=>x.id==='plave-tour-2026')?.admission==='ticketed');
assert.ok(published.events.find(x=>x.id==='suntec-lego-f1-2026')?.admission==='check');
assert.equal(eventFreshness(intake.events[0],'2026-11-12'),'review-needed');
assert.equal(new Set(published.events.map(normalizedKey)).size,published.events.length);
const rejected=compileEvents({...intake,events:[...intake.events,{...intake.events[0],id:'duplicate-art-riot'}]},sources,published.asOf);
assert.ok(rejected.rejected.some(x=>x.reason==='duplicate'));
assert.equal(compileEvents(intake,sources,'2027-01-01').events.length,0);
for(const e of published.events){
 assert.ok(sources.sources.some(s=>s.id===e.sourceId));
 assert.match(e.sourceUrl,/^https:\/\//);
 assert.ok(e.verifiedAt<=published.asOf);
}
for(const p of ['/app-events-v470.js','/lib/events-v470.mjs','/lib/events-i18n-v470.mjs','/events-v470.css','/data/events-v470.json']) assert.ok(readFileSync('sw.js','utf8').includes(p));
assert.ok(readFileSync('app-v090.js','utf8').includes("import('/app-events-v470.js')"));
assert.ok(readFileSync('index.html','utf8').includes('events-v470.css'));
assert.ok(readFileSync('scripts/audit-app-v380.mjs','utf8').includes('data/events-v470.json'));
console.log('V4.7 verified event QA passed; '+published.events.length+' sourced listings, '+sources.sources.length+' candidates.');
