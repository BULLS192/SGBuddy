import assert from 'node:assert/strict';
import {newTrip,addStop,editStop,STORE_KEY,hydrate} from '../lib/trip-v260.mjs';
import {calendarForTrip,foldIcsLine,escapeIcsText} from '../lib/trip-calendar-v421.mjs';
const t=newTrip('SG; trip\\ private','2026-11-21',2);
assert.ok(addStop(t,0,{id:'garden',name:'Gardens, Bay; 🪴',area:'Marina Bay',address:'18 Marina Gardens Drive'}));
assert.ok(addStop(t,0,{id:'merlion',name:'Merlion',area:'Marina Bay'}));
assert.ok(addStop(t,1,{id:'museum',name:'Museum',area:'Central'}));
editStop(t.days[0][0],'time','09:30');editStop(t.days[0][0],'note','Bring water; then\\walk\nLine 2');
editStop(t.days[1][0],'time','14:00');
const before=JSON.stringify(t);
const data=calendarForTrip(t,{timestamp:new Date('2026-10-15T03:00:00.000Z')});
assert.equal(data.included,2);
assert.equal(data.skipped.length,1);
assert.ok(data.content.startsWith('BEGIN:VCALENDAR\r\nVERSION:2.0\r\n'));
assert.ok(data.content.endsWith('END:VCALENDAR\r\n'));
assert.ok(data.content.includes('DTSTART;TZID=Asia/Singapore:20261121T093000'));
assert.ok(data.content.includes('DTSTART;TZID=Asia/Singapore:20261122T140000'));
assert.ok(data.content.includes('DTSTAMP:20261015T030000Z'));
assert.ok(data.content.includes('SUMMARY:Gardens\\, Bay\\; 🪴'));
assert.ok(data.content.includes('Bring water\\; then\\\\walk\\nLine 2'));
assert.ok(!data.content.includes('DTEND'),'Do not invent activity durations');
assert.ok(!data.content.includes('BEGIN:VALARM'),'No unsolicited alerts');
assert.ok(!data.content.includes('ATTENDEE'),'Never expose contacts');
assert.ok(!data.content.includes('URL:'),'Never expose hidden private links');
assert.equal(JSON.stringify(t),before,'No mutation');
assert.equal(STORE_KEY,'sgbuddy-my-trips-v260');
assert.equal(hydrate({trips:[t],activeId:t.id}).trips[0].days[0][0].time,'09:30');
assert.deepEqual(calendarForTrip(newTrip('Empty','2026-11-21',1),{timestamp:new Date(0)}).skipped,[]);
assert.throws(()=>calendarForTrip({startDate:'2026-02-30',days:[[]]}));
assert.equal(escapeIcsText('a,b;c\\d\nnext'),'a\\,b\\;c\\\\d\\nnext');
const folded=foldIcsLine('SUMMARY:'+('é'.repeat(90)));
for(const line of folded.split('\r\n'))assert.ok(new TextEncoder().encode(line).length<=75,'Fold by bytes');
console.log('V4.21 CALENDAR PASS: timed-only event markers, SG local clock, privacy, Unicode escaping/folding, unchanged storage.');
